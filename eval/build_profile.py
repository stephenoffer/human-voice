#!/usr/bin/env python3
"""Build the committed human function-word reference profile.

Burrows's Delta, the standard stylometric distance, compares a document's
function-word frequencies against a reference population after z-scoring each
word. This script builds that reference from `eval/corpus/human/` and writes it
to the linter's `human_reference_profile.json`, so the shipped skill can report a
distance without a dependency, a model, or a network call.

Run it after the human corpus changes:

    python3 eval/build_profile.py            # regenerate
    python3 eval/build_profile.py --check    # fail if the committed file drifted

Read `skills/human-voice/references/competitive-landscape.md` before you act on
the number this produces. The naive reading of the stylometry literature is that
AI text sits far from the human profile. On this corpus it sits *closer* to the
human mean than human writing does, because a model writes the average of the
population while any individual writer is idiosyncratic. The metric is reported,
never scored, and it is read in the opposite direction from the obvious one.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import statistics as st
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SCRIPTS = os.path.join(ROOT, "skills", "human-voice", "scripts")
sys.path.insert(0, SCRIPTS)

from human_voice_linter import textutil as tu  # noqa: E402

CORPUS = os.path.join(HERE, "corpus", "human")
OUT = os.path.join(SCRIPTS, "human_reference_profile.json")

# How many of the most frequent human-corpus words form the feature set. Burrows
# used 100-150; the standard result is that the metric is stable across that
# range and degrades once rare, topic-bearing words enter the vector.
FEATURE_COUNT = 150
# Documents shorter than this produce frequency estimates too noisy to compare.
MIN_WORDS = 80

WORD_RE = re.compile(r"[a-z][a-z'’-]*")


def tokens(path: str) -> list:
    raw = open(path, encoding="utf-8").read()
    prose = tu.prose_for_metrics(tu.strip_code(tu.blank_frontmatter(
        tu.normalize_text(raw))))
    return WORD_RE.findall(prose.lower())


def build() -> dict:
    docs = []
    for fn in sorted(os.listdir(CORPUS)):
        if not fn.endswith(".md"):
            continue
        w = tokens(os.path.join(CORPUS, fn))
        if len(w) >= MIN_WORDS:
            docs.append(w)
    if len(docs) < 10:
        raise SystemExit("need at least 10 human documents; found %d" % len(docs))

    pooled = Counter()
    for w in docs:
        pooled.update(w)
    features = [w for w, _ in pooled.most_common(FEATURE_COUNT)]

    vectors = []
    for w in docs:
        n = len(w)
        c = Counter(w)
        vectors.append([c[f] / n for f in features])

    mean = [round(st.mean(col), 8) for col in zip(*vectors)]
    # Population stdev, floored so a feature that never varies cannot divide by
    # zero. A zero-variance feature carries no authorial information anyway.
    stdev = [round(max(st.pstdev(col), 1e-6), 8) for col in zip(*vectors)]

    deltas = sorted(_delta(v, mean, stdev) for v in vectors)
    return {
        "_note": ("Human function-word reference profile for a Burrows's Delta "
                  "distance. Generated by eval/build_profile.py from "
                  "eval/corpus/human/. Reported by the linter, never scored: see "
                  "references/competitive-landscape.md for why a LOW delta is the "
                  "suspicious direction."),
        "feature_count": FEATURE_COUNT,
        "min_words": MIN_WORDS,
        "documents": len(docs),
        "features": features,
        "mean": mean,
        "stdev": stdev,
        # The human range, so the linter can say what "low" means without the
        # reader having to hold a distribution in their head.
        "human_delta_min": round(deltas[0], 4),
        "human_delta_median": round(st.median(deltas), 4),
        "human_delta_mean": round(st.mean(deltas), 4),
        "human_delta_max": round(deltas[-1], 4),
    }


def _delta(vec, mean, stdev) -> float:
    return sum(abs((vec[i] - mean[i]) / stdev[i])
               for i in range(len(mean))) / len(mean)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="fail if the committed profile differs from a rebuild")
    args = ap.parse_args()
    fresh = build()
    if args.check:
        if not os.path.exists(OUT):
            print("profile --check: MISSING %s" % OUT)
            return 1
        committed = json.load(open(OUT, encoding="utf-8"))
        if committed != fresh:
            print("profile --check: DRIFT. Regenerate with "
                  "`python3 eval/build_profile.py` and review the diff.")
            return 1
        print("profile --check: OK (%d features from %d human documents)"
              % (fresh["feature_count"], fresh["documents"]))
        return 0
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(fresh, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    print("wrote %s  (%d features, %d documents, human delta %.3f-%.3f, median %.3f)"
          % (OUT, fresh["feature_count"], fresh["documents"],
             fresh["human_delta_min"], fresh["human_delta_max"],
             fresh["human_delta_median"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
